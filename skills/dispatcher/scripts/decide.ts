// The workshop's decisions, kept apart from the `gh api` calls that feed them so
// they can be tested: which issues are dispatched and what happens to each PR.
// Pinned by decide.test.ts to Meridian's behaviour before the move.

import type { Blocker } from "./bodyBlockers.ts";
import type { GhCheckRun, GhComment, GhReview } from "./github.ts";

export const TIERS = ["haiku", "sonnet", "opus"];

// Ends every `switch` over a union: tsc then flags each one a new member isn't handled in.
export const assertNever = (x: never): never => {
  throw new Error(`unhandled state: ${JSON.stringify(x)}`);
};
export const AUTOMERGE = "automerge";
// The maintainer's go-ahead. Agents pick the tier; only the maintainer, or a
// relay of their digest reply, adds this.
export const READY = "ready-for-agent";
// An issue that needs the maintainer to decide something says so in its body.
export const DECISION = "Decision needed";

// The first paragraph of a body's `## <heading>` section, on one line and cut
// to 200 characters; `heading` itself when the section is empty. Undefined when
// there is no section or `settled` matches it.
const sectionParagraph = (
  body: string | null | undefined,
  heading: string,
  settled?: RegExp,
): string | undefined => {
  const m = (body ?? "").match(new RegExp(`^##\\s+${heading}\\s*$([^]*?)(?=^##\\s|(?![^]))`, "im"));
  if (!m || settled?.test(m[1])) return;
  const first = m[1].trim().split(/\n\s*\n/)[0].replace(/\s+/g, " ");
  return first.length > 200 ? `${first.slice(0, 199)}…` : first || heading;
};

/**
 * The open question in an issue body's `## Decision needed` section: its first
 * paragraph, or undefined when there is no section or it has a `Decided:` line.
 */
export const openQuestion = (body: string | null | undefined) =>
  sectionParagraph(body, DECISION, /^\s*(\*\*)?Decided:/im);

/**
 * The manual step in an issue body's `## After merge` section: its first
 * paragraph, or undefined when there is no section.
 */
export const afterMerge = (body: string | null | undefined) => sectionParagraph(body, "After merge");
export const FOLLOWUP = "<!-- workshop-followup -->";
export const AGENT = /Generated by \[Claude Code\]/;
export const FAILED = ["failure", "timed_out", "startup_failure"];
export const DEFERRED = "`deferred`; remove the label to queue it";

export const tierOf = (labels: string[]) => labels.find((l) => TIERS.includes(l));

// Comments written before the farm → workshop rename still carry `farm-` markers.
export const marked = (c: { body: string }, m: string) =>
  c.body.includes(m) || c.body.includes(m.replace("workshop", "farm"));

export const isDigest = (title: string) => /^(Workshop|Farm) digest/.test(title);

const mentions = (body: string | null | undefined, keywords: string): number[] =>
  [...(body ?? "").matchAll(new RegExp(`\\b(?:${keywords})\\s+#(\\d+)`, "gi"))].map((m) => Number(m[1]));

// Issues a PR body says it closes.
export const linkedIssues = (body: string | null | undefined): number[] =>
  mentions(body, "close[sd]?|fix(?:e[sd])?|resolve[sd]?");

// Issues a PR body closes or only references (`Refs #n`, which leaves them open).
export const referencedIssues = (body: string | null | undefined): number[] =>
  mentions(body, "close[sd]?|fix(?:e[sd])?|resolve[sd]?|refs?");

const days = (today: Date, iso: string) => (+today - +new Date(iso)) / 864e5;

/**
 * What the workshop does with an open issue, the first matching rule winning:
 * - `dispatchable`: start a session on it
 * - `elsewhere`: shown by its PR, Unstick or the digest itself, not as an issue
 * - `decision`: Waiting on you, with its open question
 * - `afterMerge`: Waiting on you, with its manual step: its PR has merged
 * - `awaitingTriage`: Waiting on you for the go-ahead
 * - `deferred`, `blocked`: Not picked up, but only counted in the digest
 * - `notPicked`: Not picked up, with the `reason` listed there
 */
export type IssueState =
  | { kind: "dispatchable" }
  | { kind: "elsewhere" }
  | { kind: "decision"; question: string }
  | { kind: "afterMerge"; step: string; pr: string }
  | { kind: "awaitingTriage" }
  | { kind: "deferred" }
  | { kind: "blocked"; blockers: ResolvedBlocker[] }
  | { kind: "notPicked"; reason: string };

/** An open blocker, or one that couldn't be looked up and so blocks until it can be. */
export type ResolvedBlocker = Blocker & { unreadable?: boolean };

export type IssueFacts = {
  title: string;
  labels: string[];
  assignees: number;
  subIssues: number;
  /** An open PR closes or references it. */
  linked: boolean;
  /** The open issues it waits on. */
  blockers: ResolvedBlocker[];
  /** Its open question (`openQuestion`). */
  question?: string;
  /** Its `## After merge` step and the merged PR it waits on, once one has merged. */
  afterMerge?: { step: string; pr: string };
};

export const issueState = (issue: IssueFacts): IssueState => {
  const l = issue.labels;
  if (isDigest(issue.title) || issue.subIssues > 0) return { kind: "elsewhere" };
  if (issue.linked) return { kind: "elsewhere" };
  // Assigned by the dispatch that made its PR, but the work is done: never again.
  if (issue.afterMerge) return { kind: "afterMerge", ...issue.afterMerge };
  if (issue.assignees) return { kind: "elsewhere" };
  if (l.includes("deferred")) return { kind: "deferred" };
  const blocked = (): IssueState => ({ kind: "blocked", blockers: issue.blockers });
  // A decision can wait until its blocker is done; the go-ahead settles it.
  if (issue.question && !l.includes(READY))
    return issue.blockers.length ? blocked() : { kind: "decision", question: issue.question };
  if (!tierOf(l) && !l.includes("opus-plan"))
    return { kind: "notPicked", reason: "no tier label; add `haiku`, `sonnet` or `opus` to queue it" };
  if (l.includes("opus-plan"))
    return { kind: "notPicked", reason: "`opus-plan`; start a plan session by hand" };
  if (issue.blockers.length) return blocked();
  if (!l.includes(READY)) return { kind: "awaitingTriage" };
  return { kind: "dispatchable" };
};

const refText = (b: Blocker) => `${b.repo}#${b.number}`;
export const blockedText = (blockers: ResolvedBlocker[]) =>
  [
    ...(blockers.some((b) => !b.unreadable)
      ? [`blocked by ${blockers.filter((b) => !b.unreadable).map(refText).join(", ")}`]
      : []),
    ...blockers.filter((b) => b.unreadable).map((b) => `blocker ${refText(b)} unreadable`),
  ].join("; ");

export type Feedback = GhComment | GhReview;

type Facts = { conflict: boolean; failing: GhCheckRun[]; feedback: Feedback[] };
type Verdict =
  | { kind: "wait"; why: string }
  | { kind: "review"; why?: string }
  | { kind: "merge" }
  | { kind: "unstick"; why: string }
  | { kind: "followup" };

/**
 * What the workshop does with an open, non-draft PR, with the `conflict`,
 * `failing` checks and `feedback` behind it:
 * - `wait`: CI still running, mergeability not computed yet, native auto-merge
 *   on it, or a follow-up still working
 * - `review`: green and quiet, waits for the maintainer; `why` says so when an
 *   `automerge` PR on `claude/issue-N` has a description that doesn't reference #N
 *   (a session that opened its PR with another session's description)
 * - `merge`: green, quiet and labelled `automerge`
 * - `unstick`: at its follow-up cap, or a follow-up went stale; `why` says which
 * - `followup`: conflict, red CI or human feedback newer than the head commit
 */
export type PrVerdict = Facts & Verdict;

export type PrFacts = {
  dependabot: boolean;
  labels: string[];
  autoMerge: boolean;
  runs: GhCheckRun[];
  mergeable: boolean | null;
  headDate: string;
  /** The PR's head branch and description, for the `claude/issue-N` check. */
  branch?: string;
  body?: string | null;
  comments: GhComment[];
  reviewComments: GhComment[];
  reviews: GhReview[];
  today: Date;
  maxFollowups: number;
  staleDays: number;
  /** The branch a conflict is with (default `main`). */
  base?: string;
};

export const prVerdict = (pr: PrFacts): PrVerdict => {
  // GitHub runs no CI on a conflicting PR, so this check must not wait for CI.
  // `mergeable` is computed lazily: null means look again next run, not conflict.
  const conflict = pr.mergeable === false;
  const finished =
    pr.runs.length > 0 && pr.runs.every((r) => r.status === "completed");
  const failing = finished
    ? pr.runs.filter((r) => FAILED.includes(r.conclusion ?? ""))
    : [];
  let feedback: Feedback[] = [];
  const out = (v: Verdict): PrVerdict => ({ ...v, conflict, failing, feedback });
  if (!finished && !conflict) return out({ kind: "wait", why: "CI running" });
  feedback = [
    ...pr.comments,
    ...pr.reviewComments,
    ...pr.reviews.filter((r) => r.body || r.state === "CHANGES_REQUESTED"),
  ].filter(
    (c) =>
      new Date("created_at" in c ? c.created_at : c.submitted_at) > new Date(pr.headDate) &&
      c.user.type !== "Bot" &&
      !AGENT.test(c.body ?? ""),
  );
  if (failing.length === 0 && feedback.length === 0 && !conflict) {
    // Each repo's Dependabot workflow labels all but majors `automerge`, and
    // drops the label when anyone else pushes; those wait for a human. The
    // script merges rather than GitHub's auto-merge because a merge with the
    // workflow token starts no deploy. Native auto-merge set earlier still runs.
    // Green but not yet known to merge cleanly: neither ask the maintainer nor merge.
    if (pr.mergeable == null) return out({ kind: "wait", why: "mergeability unknown" });
    if (!pr.autoMerge && !pr.labels.includes(AUTOMERGE)) return out({ kind: "review" });
    if (pr.autoMerge) return out({ kind: "wait", why: "auto-merge enabled" });
    const n = /^claude\/issue-(\d+)$/.exec(pr.branch ?? "")?.[1];
    if (n && !referencedIssues(pr.body).includes(Number(n)))
      return out({ kind: "review", why: `branch is for #${n} but the description doesn't reference it` });
    return out({ kind: "merge" });
  }
  const marks = pr.comments.filter((c) => marked(c, FOLLOWUP));
  const last = marks.at(-1);
  const pending = last && new Date(last.created_at) > new Date(pr.headDate);
  if (
    marks.length >= pr.maxFollowups ||
    (last && pending && days(pr.today, last.created_at) > pr.staleDays)
  )
    return out({
      kind: "unstick",
      why: `${conflict ? `conflicts with ${pr.base ?? "main"}` : failing.length ? "CI red" : "unanswered review"} after ${marks.length} follow-up(s)`,
    });
  if (pending) return out({ kind: "wait", why: "follow-up pending" });
  return out({ kind: "followup" });
};

/**
 * An assigned issue with no open PR: `notPicked` when assigned by hand (no
 * dispatch marker) and tier-labelled, `unstick` when dispatched over `staleDays`
 * ago, `inProgress` when dispatched more recently, `none` otherwise.
 */
export type ClaimState =
  | { kind: "notPicked" }
  | { kind: "unstick" }
  | { kind: "inProgress" }
  | { kind: "none" };

export const claimState = ({
  tiered,
  dispatchedAt,
  today,
  staleDays,
}: {
  tiered: boolean;
  dispatchedAt: string | null;
  today: Date;
  staleDays: number;
}): ClaimState => {
  if (!dispatchedAt) return { kind: tiered ? "notPicked" : "none" };
  return { kind: days(today, dispatchedAt) > staleDays ? "unstick" : "inProgress" };
};
