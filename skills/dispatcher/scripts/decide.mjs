// The workshop's decisions, kept apart from the `gh api` calls that feed them so
// they can be tested: which issues are dispatched and what happens to each PR.
// Pinned by decide.test.mjs to Meridian's behaviour before the move.

export const TIERS = ["haiku", "sonnet", "opus"];
export const AUTOMERGE = "automerge";
// The maintainer's go-ahead. Agents pick the tier; only the maintainer, or a
// relay of their digest reply, adds this.
export const READY = "ready-for-agent";
export const AWAITING_TRIAGE = `no \`${READY}\`; add it to queue it`;
// An issue that needs the maintainer to decide something says so in its body.
export const DECISION = "Decision needed";

/**
 * The open question in an issue body's `## Decision needed` section: its first
 * paragraph, or undefined when there is no section or it has a `Decided:` line.
 */
export const openQuestion = (body) => {
  const m = (body ?? "").match(/^##\s+Decision needed\s*$([^]*?)(?=^##\s|(?![^]))/im);
  if (!m || /^\s*(\*\*)?Decided:/im.test(m[1])) return;
  const first = m[1].trim().split(/\n\s*\n/)[0].replace(/\s+/g, " ");
  return first.length > 200 ? `${first.slice(0, 199)}…` : first || DECISION;
};
export const FOLLOWUP = "<!-- workshop-followup -->";
export const AGENT = /Generated by \[Claude Code\]/;
export const FAILED = ["failure", "timed_out", "startup_failure"];

export const tierOf = (labels) => labels.find((l) => TIERS.includes(l));

// Comments written before the farm → workshop rename still carry `farm-` markers.
export const marked = (c, m) =>
  c.body.includes(m) || c.body.includes(m.replace("workshop", "farm"));

export const isDigest = (title) => /^(Workshop|Farm) digest/.test(title);

// Issues a PR body says it closes.
export const linkedIssues = (body) =>
  [
    ...(body ?? "").matchAll(
      /\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\s+#(\d+)/gi,
    ),
  ].map((m) => Number(m[1]));

const days = (today, iso) => (today - new Date(iso)) / 864e5;

/**
 * Why an open issue isn't dispatched: undefined = dispatchable, null = shown
 * elsewhere in the digest (its PR, Unstick, the digest itself), `DECISION` or
 * `AWAITING_TRIAGE` = listed under Waiting on you, any other string = listed under
 * Not picked up with that reason. The first matching reason wins.
 * @param {{title: string, labels: string[], assignees: number, subIssues: number,
 *   linked: boolean, blockers: number[], question?: string}} issue  `linked`: an
 *   open PR closes it; `blockers`: the open issues it waits on; `question`: its
 *   open question (`openQuestion`).
 * @param {{ref?: (n: number) => string}} [opts]  how to name a blocker
 */
export const skipReason = (issue, { ref = (n) => `#${n}` } = {}) => {
  const l = issue.labels;
  if (isDigest(issue.title) || issue.subIssues > 0) return null;
  if (issue.linked || issue.assignees) return null;
  if (l.includes("deferred")) return "`deferred`; remove the label to queue it";
  // A decision can wait until its blocker is done; the go-ahead settles it.
  if (issue.question && !l.includes(READY))
    return issue.blockers.length ? blockedText(issue.blockers, ref) : DECISION;
  if (!tierOf(l) && !l.includes("opus-plan"))
    return "no tier label; add `haiku`, `sonnet` or `opus` to queue it";
  if (l.includes("opus-plan"))
    return "`opus-plan`; start a plan session by hand";
  if (issue.blockers.length) return blockedText(issue.blockers, ref);
  if (!l.includes(READY)) return AWAITING_TRIAGE;
};

export const blockedText = (blockers, ref = (n) => `#${n}`) =>
  `blocked by ${blockers.map(ref).join(", ")}`;

/**
 * What the workshop does with an open, non-draft PR:
 * - `wait`: CI still running, native auto-merge on it, or a follow-up still working
 * - `review`: green and quiet, waits for the maintainer
 * - `merge`: green, quiet and labelled `automerge` (never Dependabot's)
 * - `unstick`: at its follow-up cap, or a follow-up went stale; `why` says which
 * - `followup`: conflict, red CI or human feedback newer than the head commit
 * @param {{dependabot: boolean, labels: string[], autoMerge: boolean,
 *   runs: {status: string, conclusion: string|null}[], mergeable: boolean|null,
 *   headDate: string, comments: object[], reviewComments: object[], reviews: object[],
 *   today: Date, maxFollowups: number, staleDays: number, base?: string}} pr
 *   `base`: the branch a conflict is with (default `main`)
 */
export const prVerdict = (pr) => {
  // GitHub runs no CI on a conflicting PR, so this check must not wait for CI.
  // `mergeable` is computed lazily: null means look again next run, not conflict.
  const conflict = pr.mergeable === false;
  const finished =
    pr.runs.length > 0 && pr.runs.every((r) => r.status === "completed");
  const failing = finished
    ? pr.runs.filter((r) => FAILED.includes(r.conclusion))
    : [];
  const out = (verdict, why) => ({ verdict, why, conflict, failing, feedback });
  let feedback = [];
  if (!finished && !conflict) return out("wait", "CI running");
  feedback = [
    ...pr.comments,
    ...pr.reviewComments,
    ...pr.reviews.filter((r) => r.body || r.state === "CHANGES_REQUESTED"),
  ].filter(
    (c) =>
      new Date(c.created_at ?? c.submitted_at) > new Date(pr.headDate) &&
      c.user.type !== "Bot" &&
      !AGENT.test(c.body ?? ""),
  );
  if (failing.length === 0 && feedback.length === 0 && !conflict) {
    // Dependabot's policy is native auto-merge: its own workflow queues all but
    // majors, and drops a PR anyone else pushed to; those wait for a human.
    if (pr.dependabot ? !pr.autoMerge : !pr.labels.includes(AUTOMERGE))
      return out("review");
    return pr.autoMerge ? out("wait", "auto-merge enabled") : out("merge");
  }
  const marks = pr.comments.filter((c) => marked(c, FOLLOWUP));
  const last = marks.at(-1);
  const pending = last && new Date(last.created_at) > new Date(pr.headDate);
  if (
    marks.length >= pr.maxFollowups ||
    (pending && days(pr.today, last.created_at) > pr.staleDays)
  )
    return out(
      "unstick",
      `${conflict ? `conflicts with ${pr.base ?? "main"}` : failing.length ? "CI red" : "unanswered review"} after ${marks.length} follow-up(s)`,
    );
  if (pending) return out("wait", "follow-up pending");
  return out("followup");
};

/**
 * An assigned issue with no open PR: `notPicked` when assigned by hand (no
 * dispatch marker) and tier-labelled, `unstick` when dispatched over `staleDays`
 * ago, null otherwise.
 */
export const claimState = ({ tiered, dispatchedAt, today, staleDays }) => {
  if (!dispatchedAt) return tiered ? "notPicked" : null;
  return days(today, dispatchedAt) > staleDays ? "unstick" : null;
};
